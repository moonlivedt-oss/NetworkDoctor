"""
NetworkDoctor — сетевой доктор для Windows.

Помогает, когда после частого включения/выключения VPN-туннелей и прокси
интернет «слетает»: застревает мёртвый прокси, ломается Winsock, кешируется
DNS отключённых VPN-серверов.

Код разложен по модулям и подпакетам:
  core            — права админа, запуск команд, ps_quote, общие константы
  logs            — файловые логи, история состояний, отчёты
  settings        — пользовательские настройки (config.json)
  updates         — проверка обновлений на GitHub
  autostart       — автозапуск с Windows
  workers         — фоновые потоки (QThread): диагностика, починка, монитор
  app             — главное окно и точка входа
  net/            — сетевая логика (без Qt):
    net.tools       процессы, адаптеры, DNS, внешний IP, скорость, соединения, MTU
    net.diagnostics проверки сети (прокси, адаптеры, связь, остатки VPN)
    net.fixes       починка (прокси, WPAD, DNS, IP, Winsock/TCP, файрвол,
                    маршруты, MTU, ARP, hosts) + бэкапы перед сбросами
    net.hosts       путь, разбор и оценка подозрительности записей файла hosts
  ui/             — представление (Qt):
    ui.theme        тёмная/светлая палитры, стили, иконка, спиннер
    ui.dialogs      диалоговые окна

Автор: собрано с Claude Code.
"""

